#!/usr/bin/env python3
"""Quarantine the historical experiment registry without deleting records.

Every record in the source JSONL is retained under ``records`` as historical
evidence. These records are NOT research evidence: the registry was produced
by synthetic self-tests and test contamination, has no dataset digests, and
must never be presented as an accepted research result.

Usage:
  python3 scripts/quarantine_experiments.py [--input PATH] [--output PATH]
  python3 scripts/quarantine_experiments.py --verify [--output PATH]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = "data/assurance/experiments.jsonl"
DEFAULT_OUTPUT = "data/assurance/research-experiment-quarantine.json"
SOURCE_PATH = DEFAULT_INPUT
SCHEMA_VERSION = 1
LABEL = "HISTORICAL_QUARANTINED_RESEARCH_EVIDENCE"
RESEARCH_EVIDENCE_STATUS = "SYNTHETIC_OR_UNVERIFIED_TEST_CONTAMINATED"
ACCEPTANCE = "NOT_ACCEPTED_AS_RESEARCH"
REASON = (
    "Generated by synthetic self-tests and test contamination; records "
    "have no dataset digests and cannot substantiate research evidence."
)
NOTE = "Every source record was retained; no record was deleted or rewritten."
UNKNOWN_DIGEST = "UNKNOWN"


def resolve_path(value: str) -> Path:
    """Resolve a CLI path against the repository root unless absolute."""
    path = Path(value)
    return path if path.is_absolute() else ROOT / path


def digest_bytes(payload: bytes) -> str:
    """Return the lowercase hex SHA-256 of exact bytes."""
    return hashlib.sha256(payload).hexdigest()


def records_digest(records: list[dict]) -> str:
    """Digest the ordered records array as canonical JSON."""
    encoded = json.dumps(records, sort_keys=True, separators=(",", ":"))
    return digest_bytes(encoded.encode("utf-8"))


def read_source(path: Path) -> tuple[list[dict], str, bool]:
    """Read every JSONL record and digest the exact source bytes.

    A missing source is an honest empty result: a fresh checkout has no
    generated experiment registry and must not fail the bundle gate.
    """
    if not path.is_file():
        return [], UNKNOWN_DIGEST, False
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ValueError(f"{SOURCE_PATH}: invalid UTF-8: {exc}") from exc
    records: list[dict] = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ValueError(
                f"{SOURCE_PATH}:{number}: invalid JSON: {exc}"
            ) from exc
        if not isinstance(record, dict):
            raise ValueError(f"{SOURCE_PATH}:{number}: record is not an object")
        records.append(record)
    return records, digest_bytes(raw), True


def build_document(
    records: list[dict], source_digest: str, source_present: bool
) -> dict:
    """Build the labelled, canonicalisable quarantine document."""
    return {
        "schema_version": SCHEMA_VERSION,
        "label": LABEL,
        "research_evidence_status": RESEARCH_EVIDENCE_STATUS,
        "acceptance": ACCEPTANCE,
        "reason": REASON,
        "source_path": SOURCE_PATH,
        "source_sha256": source_digest,
        "source_present": source_present,
        "record_count": len(records),
        "records": records,
        "records_digest": records_digest(records),
        "historical": True,
        "note": NOTE,
    }


def canonical_bytes(document: dict) -> bytes:
    """Return canonical JSON bytes with two-space indent and sorted keys."""
    return (json.dumps(document, indent=2, sort_keys=True) + "\n").encode(
        "utf-8"
    )


def write_document(path: Path, document: dict) -> None:
    """Write one canonical quarantine document, creating parent directories."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(canonical_bytes(document))


def generate(input_path: Path, output_path: Path) -> dict:
    """Read the registry and write its quarantined form to ``output_path``."""
    records, source_digest, present = read_source(input_path)
    document = build_document(records, source_digest, present)
    write_document(output_path, document)
    return document


def validate_document(document: object) -> list[str]:
    """Return precise fail-closed errors for one quarantine document."""
    if not isinstance(document, dict):
        return ["quarantine document is not a JSON object"]
    errors: list[str] = []
    expected = {
        "schema_version": SCHEMA_VERSION,
        "label": LABEL,
        "research_evidence_status": RESEARCH_EVIDENCE_STATUS,
        "acceptance": ACCEPTANCE,
        "reason": REASON,
        "source_path": SOURCE_PATH,
        "note": NOTE,
    }
    for key, value in expected.items():
        if document.get(key) != value:
            errors.append(f"{key} mismatch: {document.get(key)!r}")
    if document.get("historical") is not True:
        errors.append("historical marker is missing")
    count = document.get("record_count")
    records = document.get("records")
    if isinstance(count, bool) or not isinstance(count, int) or count < 0:
        errors.append(f"record_count invalid: {count!r}")
    elif not isinstance(records, list):
        errors.append("records is not an array")
    elif len(records) != count:
        errors.append(
            f"record_count mismatch: {count} != {len(records)} records"
        )
    present = document.get("source_present")
    if not isinstance(present, bool):
        errors.append(f"source_present invalid: {present!r}")
    digest = document.get("source_sha256")
    if present is False and digest != UNKNOWN_DIGEST:
        errors.append(f"source_sha256 mismatch: {digest!r}")
    if (
        present is True
        and digest != UNKNOWN_DIGEST
        and (
            not isinstance(digest, str)
            or len(digest) != 64
            or not set(digest) <= frozenset("0123456789abcdef")
        )
    ):
        errors.append("source_sha256 is not a lowercase hex digest")
    declared_records_digest = document.get("records_digest")
    if (
        not isinstance(declared_records_digest, str)
        or len(declared_records_digest) != 64
        or not set(declared_records_digest) <= frozenset("0123456789abcdef")
    ):
        errors.append("records_digest is not a lowercase hex digest")
    elif isinstance(records, list):
        expected_records_digest = records_digest(records)
        if declared_records_digest != expected_records_digest:
            errors.append(
                "records_digest mismatch with records: "
                f"{declared_records_digest} != {expected_records_digest}"
            )
    return sorted(errors)


def verify(input_path: Path, output_path: Path) -> list[str]:
    """Compare an existing document with the source and its required labels."""
    if not output_path.is_file():
        return [f"quarantine document not found: {output_path.name}"]
    text = output_path.read_text(encoding="utf-8")
    try:
        document = json.loads(text)
    except json.JSONDecodeError as exc:
        return [f"invalid quarantine JSON: {exc}"]
    errors = validate_document(document)
    records, source_digest, present = read_source(input_path)
    if isinstance(document, dict):
        if document.get("source_present") is not present:
            errors.append(
                f"source_present mismatch: {document.get('source_present')!r}"
            )
        if present and document.get("source_sha256") != source_digest:
            errors.append("source_sha256 mismatch with source bytes")
        count = document.get("record_count")
        if (
            count != len(records)
            and isinstance(count, int)
            and not isinstance(count, bool)
        ):
            errors.append(
                f"record_count mismatch with source: {count} != {len(records)}"
            )
        declared_records_digest = document.get("records_digest")
        if isinstance(declared_records_digest, str) and (
            declared_records_digest != records_digest(records)
        ):
            errors.append("records_digest mismatch with source records")
        if document.get("records") != records:
            errors.append("records content mismatch with source records")
    return sorted(errors)


def dispatch(argv: list[str] | None) -> int:
    """Generate or verify a quarantine document from the command line."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--input", default=DEFAULT_INPUT, help="source JSONL path"
    )
    parser.add_argument(
        "--output", default=DEFAULT_OUTPUT, help="quarantine JSON path"
    )
    parser.add_argument(
        "--verify", action="store_true", help="verify an existing document"
    )
    args = parser.parse_args(argv)
    source = resolve_path(args.input)
    destination = resolve_path(args.output)
    if args.verify:
        errors = verify(source, destination)
        if errors:
            for error in errors:
                print(f"VERIFY FAIL: {error}", file=sys.stderr)
            return 1
        print(f"VERIFY PASS: {SOURCE_PATH}")
        return 0
    document = generate(source, destination)
    print(
        f"Quarantine written: {destination.name} "
        f"({document['record_count']} records)"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    """Run the CLI, failing closed on unreadable or malformed input."""
    try:
        return dispatch(argv)
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
